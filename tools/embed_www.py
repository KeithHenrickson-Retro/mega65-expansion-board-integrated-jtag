#!/usr/bin/env python3
"""Embed the default web interface files (sdcard/WWW) into the firmware.

The board serves WWW/<file> from the SD card when it is there, and these
built-in copies otherwise, so the full web interface works on any card,
including a blank one. A theme on the card still overrides them.

Writes a C file of const arrays (kept in flash, not RAM). Each array has a
NUL after the data, not counted in its size, so text files can also be used
directly as C strings (the page templates).

Usage: embed_www.py --output www_assets.c FILE...
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path


def c_ident(name: str) -> str:
    return "www_" + re.sub(r"[^A-Za-z0-9]", "_", name)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--output", required=True, type=Path)
    ap.add_argument("files", nargs="+", type=Path)
    args = ap.parse_args()

    out = [
        "// Generated by tools/embed_www.py from sdcard/WWW. Do not edit.",
        '#include "www_assets.h"',
        "",
    ]
    table = []
    for path in args.files:
        data = path.read_bytes()
        ident = c_ident(path.name)
        out.append(f"static const uint8_t {ident}[{len(data) + 1}] = {{")
        body = data + b"\0"
        for i in range(0, len(body), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in body[i:i + 16]) + ",")
        out.append("};")
        out.append("")
        table.append(f'    {{ "{path.name}", {ident}, {len(data)}u }},')

    out.append("const m65_www_asset_t m65_www_assets[] = {")
    out.extend(table)
    out.append("};")
    out.append(f"const unsigned m65_www_asset_count = {len(table)}u;")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(out) + "\n"
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
